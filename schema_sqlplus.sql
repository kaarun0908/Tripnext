-- --------------------------------------------------------------------
-- VIEWS
-- --------------------------------------------------------------------
CREATE OR REPLACE VIEW view_booking_summaries AS
SELECT 
    b.id AS booking_id,
    b.booking_reference,
    u.full_name AS customer_name,
    u.email AS customer_email,
    u.phone AS customer_phone,
    CASE 
        WHEN b.package_id IS NOT NULL THEN 'Package'
        WHEN b.room_id IS NOT NULL THEN 'Hotel Room'
        ELSE 'Other'
    END AS booking_type,
    NVL(p.name, h.name || ' - ' || r.room_type) AS item_name,
    NVL(d_pkg.name, d_htl.name) AS destination_name,
    b.check_in,
    b.check_out,
    (b.check_out - b.check_in) AS duration_days,
    b.number_of_guests,
    b.total_amount,
    b.booking_status,
    pay.payment_status,
    pay.payment_method,
    pay.transaction_reference,
    b.created_at
FROM bookings b
INNER JOIN users u ON b.user_id = u.id
LEFT JOIN packages p ON b.package_id = p.id
LEFT JOIN destinations d_pkg ON p.destination_id = d_pkg.id
LEFT JOIN rooms r ON b.room_id = r.id
LEFT JOIN hotels h ON r.hotel_id = h.id
LEFT JOIN destinations d_htl ON h.destination_id = d_htl.id
LEFT JOIN payments pay ON b.id = pay.booking_id;

CREATE OR REPLACE VIEW view_destination_stats AS
SELECT 
    d.id AS destination_id,
    d.name AS destination_name,
    d.region,
    d.category,
    d.estimated_budget,
    COUNT(DISTINCT p.id) AS total_packages,
    COUNT(DISTINCT h.id) AS total_hotels,
    COUNT(DISTINCT b.id) AS total_bookings,
    NVL(SUM(CASE WHEN b.booking_status = 'CONFIRMED' THEN b.total_amount ELSE 0 END), 0) AS total_revenue
FROM destinations d
LEFT JOIN packages p ON d.id = p.destination_id
LEFT JOIN hotels h ON d.id = h.destination_id
LEFT JOIN bookings b ON (b.package_id = p.id)
GROUP BY d.id, d.name, d.region, d.category, d.estimated_budget;

-- --------------------------------------------------------------------
-- AUDIT TRIGGER: Log status change automatically
-- --------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_booking_status_audit
AFTER UPDATE OF booking_status ON bookings
FOR EACH ROW
WHEN (OLD.booking_status <> NEW.booking_status)
BEGIN
    INSERT INTO booking_status_history (
        booking_id, old_status, new_status, changed_by, changed_at, remarks
    ) VALUES (
        :OLD.id, :OLD.booking_status, :NEW.booking_status, :NEW.user_id, SYSTIMESTAMP, 'Auto-logged via Database Trigger'
    );
END;
