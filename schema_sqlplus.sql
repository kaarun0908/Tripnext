-- --------------------------------------------------------------------
-- 1. USERS TABLE
-- --------------------------------------------------------------------
CREATE TABLE users (
    id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR2(100) NOT NULL,
    email          VARCHAR2(120) NOT NULL UNIQUE,
    phone          VARCHAR2(20),
    password_hash  VARCHAR2(255) NOT NULL,
    role           VARCHAR2(20) DEFAULT 'customer' NOT NULL,
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_user_role CHECK (role IN ('customer', 'admin'))
);

-- --------------------------------------------------------------------
-- 2. DESTINATIONS TABLE
-- --------------------------------------------------------------------
CREATE TABLE destinations (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR2(100) NOT NULL,
    country           VARCHAR2(100) DEFAULT 'India' NOT NULL,
    region            VARCHAR2(100) NOT NULL,
    category          VARCHAR2(50) NOT NULL,
    description       CLOB NOT NULL,
    image_url         VARCHAR2(500) NOT NULL,
    estimated_budget  NUMBER(10, 2) NOT NULL,
    is_active         NUMBER(1) DEFAULT 1 NOT NULL,
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_dest_budget CHECK (estimated_budget >= 0),
    CONSTRAINT chk_dest_active CHECK (is_active IN (0, 1))
);

-- --------------------------------------------------------------------
-- 3. ATTRACTIONS TABLE
-- --------------------------------------------------------------------
CREATE TABLE attractions (
    id                   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id       NUMBER NOT NULL,
    name                 VARCHAR2(150) NOT NULL,
    description          CLOB NOT NULL,
    entry_fee            NUMBER(10, 2) DEFAULT 0.00 NOT NULL,
    opening_information  VARCHAR2(200),
    CONSTRAINT fk_attraction_dest FOREIGN KEY (destination_id) 
        REFERENCES destinations (id) ON DELETE CASCADE,
    CONSTRAINT chk_entry_fee CHECK (entry_fee >= 0)
);

-- --------------------------------------------------------------------
-- 4. PACKAGES TABLE
-- --------------------------------------------------------------------
CREATE TABLE packages (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id    NUMBER NOT NULL,
    name              VARCHAR2(150) NOT NULL,
    description       CLOB NOT NULL,
    duration_days     NUMBER(3) NOT NULL,
    price_per_person  NUMBER(10, 2) NOT NULL,
    inclusions        VARCHAR2(500) NOT NULL,
    image_url         VARCHAR2(500),
    is_active         NUMBER(1) DEFAULT 1 NOT NULL,
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_package_dest FOREIGN KEY (destination_id) 
        REFERENCES destinations (id) ON DELETE CASCADE,
    CONSTRAINT chk_package_days CHECK (duration_days > 0),
    CONSTRAINT chk_package_price CHECK (price_per_person >= 0)
);

-- --------------------------------------------------------------------
-- 5. PACKAGE ITINERARIES TABLE
-- --------------------------------------------------------------------
CREATE TABLE package_itineraries (
    id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id   NUMBER NOT NULL,
    day_number   NUMBER(3) NOT NULL,
    title        VARCHAR2(150) NOT NULL,
    description  CLOB NOT NULL,
    CONSTRAINT fk_itinerary_pkg FOREIGN KEY (package_id) 
        REFERENCES packages (id) ON DELETE CASCADE,
    CONSTRAINT chk_itin_day CHECK (day_number > 0)
);

-- --------------------------------------------------------------------
-- 6. HOTELS TABLE
-- --------------------------------------------------------------------
CREATE TABLE hotels (
    id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_id  NUMBER NOT NULL,
    name            VARCHAR2(150) NOT NULL,
    address         VARCHAR2(255) NOT NULL,
    description     CLOB NOT NULL,
    amenities       VARCHAR2(500) NOT NULL,
    rating          NUMBER(3, 2) DEFAULT 4.50 NOT NULL,
    image_url       VARCHAR2(500),
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_hotel_dest FOREIGN KEY (destination_id) 
        REFERENCES destinations (id) ON DELETE CASCADE,
    CONSTRAINT chk_hotel_rating CHECK (rating >= 1.0 AND rating <= 5.0)
);

-- --------------------------------------------------------------------
-- 7. ROOMS TABLE
-- --------------------------------------------------------------------
CREATE TABLE rooms (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id         NUMBER NOT NULL,
    room_type        VARCHAR2(100) NOT NULL,
    capacity         NUMBER(2) DEFAULT 2 NOT NULL,
    price_per_night  NUMBER(10, 2) NOT NULL,
    total_rooms      NUMBER(4) DEFAULT 5 NOT NULL,
    is_active        NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT fk_room_hotel FOREIGN KEY (hotel_id) 
        REFERENCES hotels (id) ON DELETE CASCADE,
    CONSTRAINT chk_room_capacity CHECK (capacity > 0),
    CONSTRAINT chk_room_price CHECK (price_per_night >= 0),
    CONSTRAINT chk_room_total CHECK (total_rooms >= 0)
);

-- --------------------------------------------------------------------
-- 8. BOOKINGS TABLE
-- --------------------------------------------------------------------
CREATE TABLE bookings (
    id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_reference VARCHAR2(30) NOT NULL UNIQUE,
    user_id           NUMBER NOT NULL,
    package_id        NUMBER,
    room_id           NUMBER,
    check_in          DATE NOT NULL,
    check_out         DATE NOT NULL,
    number_of_guests  NUMBER(3) NOT NULL,
    total_amount      NUMBER(10, 2) NOT NULL,
    booking_status    VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    special_requests  CLOB,
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_booking_user FOREIGN KEY (user_id) 
        REFERENCES users (id),
    CONSTRAINT fk_booking_package FOREIGN KEY (package_id) 
        REFERENCES packages (id) ON DELETE SET NULL,
    CONSTRAINT fk_booking_room FOREIGN KEY (room_id) 
        REFERENCES rooms (id) ON DELETE SET NULL,
    CONSTRAINT chk_booking_dates CHECK (check_out > check_in),
    CONSTRAINT chk_booking_guests CHECK (number_of_guests > 0),
    CONSTRAINT chk_booking_amount CHECK (total_amount >= 0),
    CONSTRAINT chk_booking_status CHECK (booking_status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED'))
