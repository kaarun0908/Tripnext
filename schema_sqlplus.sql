BEGIN
   FOR c IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'ROOM_RESERVATIONS', 'BOOKING_STATUS_HISTORY', 'FAVOURITES',
      'REVIEWS', 'PAYMENTS', 'BOOKINGS', 'ROOMS', 'HOTELS',
      'PACKAGE_ITINERARIES', 'PACKAGES', 'ATTRACTIONS',
      'DESTINATIONS', 'USERS'
